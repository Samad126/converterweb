/**
 * Snapshots the backend's conversion matrix into `lib/files/fileMatrix.ts`.
 *
 *   (cd ../backend && npm run build) && node scripts/gen-file-matrix.mjs
 *
 * The site cannot import the backend, and its page catalog is static, so the
 * pairs the extra conversion pages are built from are copied here once and
 * committed. Capability at runtime still comes from `GET /formats`; this file
 * only decides which pages exist.
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const { SOURCES, TARGETS } = require("../../backend/dist/formats.js");

const matrix = {};
const targets = {};
for (const [extension, source] of Object.entries(SOURCES).sort(([a], [b]) => a.localeCompare(b))) {
  matrix[extension] = [...source.targets];
  for (const id of source.targets) {
    targets[id] = { label: TARGETS[id].label, extension: TARGETS[id].extension };
  }
}

const body = `/* GENERATED by scripts/gen-file-matrix.mjs from the backend's formats.ts. Do not edit. */

export const FILE_TARGETS: Readonly<Record<string, { label: string; extension: string }>> = ${JSON.stringify(targets, null, 2)};

/** Every source extension the service accepts, and the target ids it reaches. */
export const FILE_MATRIX: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(matrix, null, 2)};
`;
writeFileSync(new URL("../lib/files/fileMatrix.ts", import.meta.url), body);
console.log(`${Object.keys(matrix).length} sources, ${Object.keys(targets).length} targets`);
